#include "header.h"

/**========================================================================
 *                           display_map
 *========================================================================**/
void	display_map(t_map *map, int y)
{
	int	i;

	i = y;
	while (i < map->map_size_y)
	{
		write(1, &map->map[i], ft_strlen(map->map[i]));
		write (1, "\n", 1);
		i++;
	}
}

/**========================================================================
 *                           ft_putstr
 *========================================================================**/
void	ft_putstr(char str[])
{
	write(1, &str, ft_strlen(str));
}
