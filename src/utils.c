#include "header.h"

/**========================================================================
 *                           close_file
 *========================================================================**/
void	close_file(int fd)
{
	if (fd != -1)
	{
		close (fd);
	}
}

/**========================================================================
 *                           open_file
 *========================================================================**/
int	open_file(int argc, t_map *map, char *file_name)
{
	map->fd = open(file_name, O_RDONLY);
	if (map->fd == -1)
		error_msg("file error\n");
	return (map->fd);
}

/**========================================================================
 *                           error_msg
 *========================================================================**/
void	error_msg(char *str)
{
	write (2, str, ft_strlen(str));
}

/**========================================================================
 *                           free_tab
 *========================================================================**/
void	free_tab(char **tab)

{
	int	i;

	i = 0;
	while (tab[i])
	{
		free(tab[i]);
		tab[i++] = NULL;
	}
	free(tab);
	tab = NULL;
}
